/**
 * Helper to safely extract translated string with dot notation fallback to English
 */
export function t(lang, keyPath) {
  const currentLang = lang === 'mr' ? 'mr' : 'en';
  const keys = keyPath.split('.');
  
  let val = TRANSLATIONS[currentLang];
  for (const k of keys) {
    if (val && typeof val === 'object') {
      val = val[k];
    } else {
      val = null;
      break;
    }
  }

  if (val) return val;

  // Fallback to English
  let fallbackVal = TRANSLATIONS['en'];
  for (const k of keys) {
    if (fallbackVal && typeof fallbackVal === 'object') {
      fallbackVal = fallbackVal[k];
    } else {
      return keyPath;
    }
  }

  return fallbackVal || keyPath;
}
